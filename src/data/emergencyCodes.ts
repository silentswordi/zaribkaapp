// Helper to normalize Persian text for searching
export function normalizePersianText(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/[ي]/g, 'ی')
    .replace(/[ك]/g, 'ک')
    .replace(/[ۀة]/g, 'ه')
    .replace(/[۰]/g, '0')
    .replace(/[۱]/g, '1')
    .replace(/[۲]/g, '2')
    .replace(/[۳]/g, '3')
    .replace(/[۴]/g, '4')
    .replace(/[۵]/g, '5')
    .replace(/[۶]/g, '6')
    .replace(/[۷]/g, '7')
    .replace(/[۸]/g, '8')
    .replace(/[۹]/g, '9')
    .replace(/[\u064B-\u065F]/g, '') // Remove arabic diacritics
    .replace(/[\s\-_/\\]+/g, ' ')
    .trim();
}

// Format numbers into Persian digits
export function toPersianDigits(n: number | string): string {
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(n).replace(/[0-9]/g, (w) => persianDigits[+w]);
}
